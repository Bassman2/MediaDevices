            var attr = field.GetAttribute(EnumGuidAttribute);
            if (attr != null)
            {
                sb.AppendLine($"            {en.Name}.{field.Name} => Guid{field.Name},");
            }
        }
        sb.AppendLine(
            $$"""
                        _ => Guid.Empty
                    };
                }
                
            """);
    }

