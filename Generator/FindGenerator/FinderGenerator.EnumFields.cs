    [System.Flags]
    internal enum FindType
    {
        Guid = 1,
        PropertyKey = 2,
        All = Guid | PropertyKey
    }

    private void CreateFindEnumFieldsFile(Enum en)
    {
        FindType findType = en.GetAttribute(FindFieldsGeneratorAttribute)?.GetConstructorArgument(0)?.ToEnum<FindType>() ?? FindType.All;

        StringBuilder sb = new(
            $$"""
            // <auto-generated />  

            #nullable enable annotations
            #nullable disable warnings

            // Suppress warnings about [Obsolete] member usage in generated code.
            #pragma warning disable CS0612, CS0618
            
            namespace {{en.NameSpace}};

            internal static class Enum{{en.Name}}GuidFinder
            {

            """);

        if (findType.HasFlag(FindType.Guid))
        {
            CreateGuidFields(sb, en);
            CreateToGuid(sb, en);
            CreateGuidToEnum(sb, en);
            CreateGuidToName(sb, en);
        }

        if (findType.HasFlag(FindType.PropertyKey))
        {

            CreatePropertyKeyFields(sb, en);
            CreateToPropertyKey(sb, en);
            CreatePropertyKeyToEnum(sb, en);
            CreatePropertyKeyToName(sb, en);
        }

        sb.AppendLine("}");

        AddSource($"Enum{en.Name}FindFields.g.cs", sb.ToString());
    }

